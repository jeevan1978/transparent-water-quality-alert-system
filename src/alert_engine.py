"""
alert_engine.py
===============
Rules and predictive intelligence engine that analyzes current readings
and forecasted future trends to issue actionable water quality alerts.

CRITICAL DISCLAIMER:
--------------------
ALERTS GENERATED BY THIS SYSTEM ARE DEMONSTRATION SIGNALS BASED ON
SIMULATED TELEMETRY. THEY MUST NOT BE USED FOR REAL MUNICIPAL DISPATCH.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
import uuid


class Alert:
    """Represents a structured water quality alert notification."""

    def __init__(
        self,
        station_id: str,
        severity: str,
        alert_type: str,
        title: str,
        description: str,
        recommended_action: str,
        parameters: Dict[str, Any],
        timestamp: Optional[datetime] = None,
        alert_source: Optional[str] = None,
        event_key: Optional[str] = None,
        event_window: Optional[str] = None,
        dedup_key: Optional[str] = None
    ):
        self.alert_id = f"ALT-{uuid.uuid4().hex[:8].upper()}"
        self.timestamp = timestamp or datetime.now()
        self.station_id = station_id
        self.severity = severity  # 'INFO', 'WARNING', 'CRITICAL'
        self.alert_type = alert_type  # 'THRESHOLD_BREACH', 'PREDICTIVE_DEGRADATION', 'SYSTEM_NOTICE'
        self.title = title
        self.description = description
        self.recommended_action = recommended_action
        self.parameters = parameters

        # Explicit alert source distinction ('CURRENT' vs 'PREDICTIVE')
        if alert_source:
            self.alert_source = alert_source
        elif alert_type == "PREDICTIVE_DEGRADATION":
            self.alert_source = "PREDICTIVE"
        else:
            self.alert_source = "CURRENT"

        # Parameter / event key for deduplication
        if event_key:
            self.event_key = event_key
        elif parameters and isinstance(parameters, dict):
            self.event_key = "_".join(sorted(parameters.keys()))
        else:
            self.event_key = title.lower().replace(" ", "_")

        # Event window / source reading representation
        if event_window:
            self.event_window = str(event_window)
        else:
            # Default to 1-hour window bucket from timestamp to absorb rapid repeated clicks/reruns
            if isinstance(self.timestamp, datetime):
                self.event_window = self.timestamp.strftime("%Y-%m-%d %H:00")
            elif isinstance(self.timestamp, str) and len(self.timestamp) >= 13:
                self.event_window = self.timestamp[:13] + ":00"
            else:
                self.event_window = str(self.timestamp)

        # Stable deduplication key
        if dedup_key:
            self.dedup_key = dedup_key
        else:
            self.dedup_key = f"{self.station_id}:{self.alert_type}:{self.severity}:{self.event_key}:{self.event_window}"

    def to_dict(self) -> Dict[str, Any]:
        """Converts alert object to JSON-compatible dictionary."""
        return {
            "alert_id": self.alert_id,
            "dedup_key": self.dedup_key,
            "alert_source": self.alert_source,
            "timestamp": self.timestamp.strftime("%Y-%m-%d %H:%M:%S") if isinstance(self.timestamp, datetime) else str(self.timestamp),
            "station_id": self.station_id,
            "severity": self.severity,
            "alert_type": self.alert_type,
            "title": self.title,
            "description": self.description,
            "recommended_action": self.recommended_action,
            "parameters": self.parameters,
        }


class WaterAlertEngine:
    """
    Evaluates telemetry readings and forecasted conditions against
    system thresholds and operational rules to dispatch alerts.
    """

    def __init__(self, thresholds_config: Optional[Dict[str, Any]] = None):
        self.thresholds = thresholds_config or {}

    def evaluate_current_reading(
        self,
        station_id: str,
        reading: Dict[str, Any]
    ) -> List[Alert]:
        """
        Generates real-time alerts based on immediate parameter breaches.

        Args:
            station_id (str): Station identifier.
            reading (Dict[str, Any]): Current sensor values.

        Returns:
            List[Alert]: Generated alert items.
        """
        alerts: List[Alert] = []
        ph = reading.get("ph", 7.0)
        turbidity = reading.get("turbidity", 1.0)
        do = reading.get("dissolved_oxygen", 7.0)
        cond = reading.get("conductivity", 300.0)
        reading_ts = reading.get("timestamp")

        # 1. Critical breaches
        if do < 4.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="CRITICAL",
                    alert_type="THRESHOLD_BREACH",
                    title="Severe Hypoxia Detected",
                    description=f"Dissolved oxygen level dropped to {do} mg/L (Critical threshold: 4.0 mg/L).",
                    recommended_action="Inspect surface aeration impellers immediately and investigate organic loading sources.",
                    parameters={"dissolved_oxygen": do},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="dissolved_oxygen"
                )
            )

        if ph < 6.0 or ph > 9.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="CRITICAL",
                    alert_type="THRESHOLD_BREACH",
                    title="Critical pH Deviation",
                    description=f"Observed pH value of {ph} violates safe operating boundary (6.0 - 9.0).",
                    recommended_action="Isolate intake manifold and initiate chemical buffer dosing diagnostics.",
                    parameters={"ph": ph},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="ph"
                )
            )

        if turbidity >= 15.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="CRITICAL",
                    alert_type="THRESHOLD_BREACH",
                    title="High Turbidity Surge",
                    description=f"Turbidity measured at {turbidity} NTU, well above 15.0 NTU critical limit.",
                    recommended_action="Activate coagulation/flocculation auxiliary stages and monitor filter backwash cycles.",
                    parameters={"turbidity": turbidity},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="turbidity"
                )
            )

        # 2. Moderate Warnings
        if 4.0 <= do < 6.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="WARNING",
                    alert_type="THRESHOLD_BREACH",
                    title="Sub-optimal Dissolved Oxygen",
                    description=f"Dissolved oxygen is sub-optimal ({do} mg/L).",
                    recommended_action="Monitor trend over the next 2 hours and increase aeration standby capacity.",
                    parameters={"dissolved_oxygen": do},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="dissolved_oxygen_warning"
                )
            )

        if 5.0 < turbidity < 15.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="WARNING",
                    alert_type="THRESHOLD_BREACH",
                    title="Elevated Turbidity Warning",
                    description=f"Turbidity is elevated at {turbidity} NTU (Warning limit: 5.0 NTU).",
                    recommended_action="Check upstream stormwater inflow or sensor optical window cleanliness.",
                    parameters={"turbidity": turbidity},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="turbidity_warning"
                )
            )

        if cond > 800.0:
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="WARNING",
                    alert_type="THRESHOLD_BREACH",
                    title="Elevated Conductivity / Dissolved Minerals",
                    description=f"Electrical conductivity is {cond} µS/cm (Warning limit: 800 µS/cm).",
                    recommended_action="Sample for salinity influx and inspect desalination/demineralization membrane.",
                    parameters={"conductivity": cond},
                    timestamp=reading_ts,
                    alert_source="CURRENT",
                    event_key="conductivity_warning"
                )
            )

        return alerts

    def evaluate_predictive_forecast(
        self,
        station_id: str,
        horizon_hours: int,
        predicted_category: str,
        predicted_params: Dict[str, Any],
        forecast_timestamp: Optional[datetime] = None
    ) -> List[Alert]:
        """
        Generates proactive early-warning alerts if future forecast projects degradation.

        Args:
            station_id (str): Station identifier.
            horizon_hours (int): Forecasting horizon (e.g. 6 or 24).
            predicted_category (str): Projected quality category ('Good', 'Needs Treatment', 'Poor').
            predicted_params (Dict[str, Any]): Forecasted parameter values.
            forecast_timestamp (datetime, optional): Base timestamp of forecast.

        Returns:
            List[Alert]: Predictive alerts if future condition degrades.
        """
        alerts: List[Alert] = []

        if predicted_category == "Poor":
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="CRITICAL",
                    alert_type="PREDICTIVE_DEGRADATION",
                    title=f"Predicted Severe Degradation (+{horizon_hours}h)",
                    description=(
                        f"Forecasting model anticipates water quality will deteriorate to 'Poor' "
                        f"within {horizon_hours} hours. Projected parameters: {predicted_params}."
                    ),
                    recommended_action="Schedule preemptive treatment adjustments and alert reservoir supervisory control.",
                    parameters=predicted_params,
                    timestamp=forecast_timestamp,
                    alert_source="PREDICTIVE",
                    event_key=f"predictive_{horizon_hours}h_poor"
                )
            )
        elif predicted_category == "Needs Treatment":
            alerts.append(
                Alert(
                    station_id=station_id,
                    severity="WARNING",
                    alert_type="PREDICTIVE_DEGRADATION",
                    title=f"Anticipated Treatment Requirement (+{horizon_hours}h)",
                    description=(
                        f"Forecasting model projects water condition shifting to 'Needs Treatment' "
                        f"in {horizon_hours} hours."
                    ),
                    recommended_action="Prepare clarification filters and review dosing inventory in advance.",
                    parameters=predicted_params,
                    timestamp=forecast_timestamp,
                    alert_source="PREDICTIVE",
                    event_key=f"predictive_{horizon_hours}h_needs_treatment"
                )
            )

        return alerts


